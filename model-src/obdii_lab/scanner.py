class ScannerSession:
    """One selected virtual adapter and target, initially disconnected."""
    def __init__(self, sim, diagnostic=None):
        self.sim = sim
        self.connected = False
        self.protocol = "can11_500"
        self.module_id = "ecu"
        self.last_request_t = None
        self.log = []
        self.diagnostic = diagnostic or DiagnosticServer(self._ecu_snapshot, sim.clear_emissions_dtcs)
        # The shared server still owns its UDS session and clear callback. Its
        # values now come from sampled channels rather than hidden plant truth.
        self.diagnostic.snapshot_fn = self._ecu_snapshot

    @property
    def configuration(self):
        if hasattr(self.sim, "configuration"):
            return self.sim.configuration
        return self.sim.snapshot().get("vehicle", {}).get("configuration", {})

    def catalog(self):
        systems = vehicle_system_catalog(self.configuration)
        protocols = deepcopy(PROTOCOLS)
        for protocol in protocols:
            if protocol["id"].startswith("can"):
                protocol["signal_states"] = [
                    {"bit": 1, "state": "Recessive", "can_h_v": 2.5, "can_l_v": 2.5, "difference_v": 0.0},
                    {"bit": 0, "state": "Dominant", "can_h_v": 3.5, "can_l_v": 1.5, "difference_v": 2.0},
                ]
                protocol["bit_interval_us"] = 1_000_000 / protocol["bitrate"]
                protocol["signal_scope"] = "Typical explanatory voltage levels, not guaranteed values for every transceiver. Bit timing, arbitration and voltage waveforms are not simulated."
        return {"schema": "obdii-lab.scanner.v2", "protocols": protocols,
                "modules": [{"id": u["id"], "label": u["label"], "installed": u["installed"],
                             "capability": u["diagnostic_capability"],
                             "description": "Executable OBD/UDS teaching endpoint" if u["id"] == "ecu" else "Simulation state inspection; no OEM diagnostic address is invented"}
                            for u in systems["units"] if u["id"] not in ("engine", "battery", "dlc", "scan_tool")],
                "socket": {"id": "dlc_socket", "label": "16-pin diagnostic connector",
                           "view": "Vehicle socket viewed from the mating face; wide edge at top, pins 1–8 above 9–16.",
                           "pins": diagnostic_pins(),
                           "note": "Assigned roles depend on the transport and vehicle. Selecting a pin only inspects it. The DLC unplug switch opens the tester CAN branch; it does not simulate separate pin faults or remove the supply/ground references."},
                "sources": deepcopy(SOURCES),
                "scope": "Virtual adapter with generated CAN/ISO-TP lesson traces. Model-state inspection of other modules is separate from a real multi-ECU protocol scan."}

    def connect(self, protocol="can11_500", module_id="ecu"):
        selected = next((p for p in PROTOCOLS if p["id"] == protocol), None)
        if selected is None:
            raise ValueError("Unknown diagnostic transport")
        if selected["availability"] != "implemented":
            raise ValueError(selected["label"] + " is reference-only; its transport is not implemented")
        module = next((u for u in self.catalog()["modules"] if u["id"] == module_id), None)
        if module is None:
            raise ValueError("Unknown diagnostic module")
        if not module["installed"]:
            raise ValueError("Selected module is not installed in this vehicle")
        self.protocol, self.module_id, self.connected = protocol, module_id, True
        return self.state()

    def disconnect(self):
        self.connected = False
        return self.state()

    def _state(self, module_id, snapshot):
        protocol = next(p for p in PROTOCOLS if p["id"] == self.protocol)
        module = next((u for u in vehicle_system_catalog(self.configuration)["units"] if u["id"] == module_id), None)
        status, reason = "ready", "Virtual adapter connected; requests use the current simulation samples."
        effective = snapshot.get("effective_connections", snapshot.get("connections", {}))
        vehicle_bitrate = self.configuration.get("can_bitrate", 500000)
        if not self.connected:
            status, reason = "disconnected", "Connect the virtual scan tool before requesting data."
        elif not module or not module["installed"]:
            status, reason = "not_installed", "The selected module is not installed in this configuration."
        elif not snapshot.get("inputs", {}).get("ignition", False):
            status, reason = "vehicle_off", "Switch the ignition on. The engine can remain stopped while the ECU responds."
        elif not effective.get("dlc", True):
            status, reason = "dlc_open", "The diagnostic branch is unplugged; the request cannot reach the vehicle."
        elif protocol["bitrate"] != vehicle_bitrate:
            status, reason = "bitrate_mismatch", "Adapter and vehicle CAN bitrates do not match."
        elif not effective.get("unit_" + module_id, True) or module_id == "bmu" and not effective.get("bmu", True):
            status, reason = "unit_open", "The selected module connector is unplugged."
        elif module_id != "ecu":
            status, reason = "state_only", "This unit supports explicit simulation-state inspection, not an implemented OEM byte-addressed endpoint."
        return {"connected": self.connected, "protocol": self.protocol, "module_id": module_id,
                "status": status, "label": protocol["label"], "bitrate": protocol["bitrate"],
                "vehicle_bitrate": vehicle_bitrate, "reason": reason,
                "last_request_t": self.last_request_t, "log_count": len(self.log)}

    def state(self):
        return self._state(self.module_id, self.sim.snapshot())

    def _ecu_snapshot(self):
        snapshot = self.sim.snapshot()
        readings = snapshot.get("vehicle_sensors", {})
        for sensor_id, field in (("crank_sensor", "rpm"), ("vehicle_speed", "speed_kph"),
                                 ("maf", "maf_g_s"), ("throttle_sensor", "throttle_pct")):
            reading = readings.get(sensor_id)
            if reading and reading.get("validity") == "valid":
                snapshot[field] = reading["value"]
        intake = readings.get("intake_temp")
        if intake and intake.get("validity") == "valid":
            snapshot.setdefault("sensors", {})["iat_c"] = intake["value"]
        return snapshot

    def _record(self, result):
        self.last_request_t = result["sample_t"]
        self.log.append(deepcopy(result))
        if len(self.log) > 256:
            del self.log[:-256]
        return result

    def _request(self, payload, can_id, module_id):
        snapshot = self.sim.snapshot()
        state = self._state(module_id, snapshot)
        result = {"request_hex": payload, "response_hex": None, "meaning": "", "frames": [],
                  "transport": "Classical CAN / normal ISO-TP (lesson trace)",
                  "sample_t": snapshot.get("t", 0), "target": module_id,
                  "connection": state, "source": "sampled simulation state"}
        try:
            if not isinstance(payload, str):
                raise ValueError("Request must be a hexadecimal text string")
            raw = bytes.fromhex(payload)
            if not 1 <= len(raw) <= 7:
                raise ValueError("Enter 1..7 application bytes; omit CAN ID, length/PCI, and padding")
            if can_id is None:
                can_id = ENGINE_REQUEST_ID if raw[0] >= 0x10 else FUNCTIONAL_ID
            if isinstance(can_id, bool) or not isinstance(can_id, int) or not 0 <= can_id <= 0x7FF:
                raise ValueError("can_id must be an integer 11-bit CAN identifier")
            result["request_hex"] = raw.hex(" ").upper()
        except (ValueError, TypeError) as exc:
            result.update(error=str(exc), meaning="Invalid request; no frames were generated.")
            return self._record(result)
        if state["status"] not in ("ready", "state_only"):
            result.update(timeout=True, status="timeout", delivery="not_delivered", meaning=state["reason"] + " No simulated reply.")
            return self._record(result)
        if module_id != "ecu":
            result.update(status="state_only", delivery="not_implemented",
                          meaning="No byte-addressed diagnostic endpoint is implemented for this module. Use module-state inspection to see its signals and stored lab events.")
            return self._record(result)
        # There is no universal OBD 'invalid sensor' numeric value. This lesson
        # declines a sample for these channels instead of returning plant truth.
        pid_sensors = {0x05: "ect", 0x0C: "crank_sensor", 0x0D: "vehicle_speed", 0x0F: "intake_temp", 0x10: "maf", 0x11: "throttle_sensor"}
        sensor = pid_sensors.get(raw[1]) if len(raw) == 2 and raw[0] == 1 else None
        reading = snapshot.get("vehicle_sensors", {}).get(sensor)
        if reading:
            result.update(sensor_id=sensor, sensor_conversion=reading.get("conversion"))
        if reading and raw[1] != 0x05 and reading.get("validity") != "valid":
            result.update(status="sample_unavailable", delivery="no_valid_sample", sensor_id=sensor,
                          meaning="No valid sampled " + sensor.replace("_", " ") + " input. Inspect the connector and fault memory. This lesson does not fabricate a numeric fallback response.")
            return self._record(result)
        response = self.diagnostic.request(result["request_hex"], can_id)
        result.update(response)
        result["bitrate"] = state["bitrate"]
        return self._record(result)

    def request(self, payload, can_id=None):
        return self._request(payload, can_id, self.module_id)

    def discover(self, protocol="can11_500"):
        """Survey the selected transport without changing the open unit session."""
        probe = ScannerSession(self.sim)
        first = next(m["id"] for m in probe.catalog()["modules"] if m["installed"])
        probe.connect(protocol, first)
        return probe.scan()

    def scan(self, module_id=None):
        if module_id is not None and module_id != self.module_id:
            raise ValueError("Connect to the requested control unit before reading its faults.")
        snapshot = self.sim.snapshot()
        systems = vehicle_system_catalog(self.configuration)
        module_map = {u["id"]: u for u in self.catalog()["modules"]}
        if module_id is not None:
            module_map = {module_id: module_map[module_id]}
        diagnostics = []
        ecu = module_map.get("ecu")
        if ecu and ecu["installed"]:
            diagnostics = [self._request("03", FUNCTIONAL_ID, "ecu"), self._request("07", FUNCTIONAL_ID, "ecu")]
        modules = []
        readings = snapshot.get("vehicle_sensors", {})
        events = snapshot.get("sensor_dtcs", {}).get("modules", {})
        for id, module in module_map.items():
            unit = next(u for u in systems["units"] if u["id"] == id)
            state = self._state(id, snapshot)
            reachable = state["status"] in ("ready", "state_only")
            codes = list(snapshot.get("dtcs", [])) if id == "ecu" else list(events.get(id, []))
            pending = list(snapshot.get("pending_dtcs", [])) if id == "ecu" else []
            if id == "bmu":
                codes += list(snapshot.get("module_dtc", {}).get("BMU", []))
            if id == "abs":
                codes += list(snapshot.get("module_dtc", {}).get("ABS_ESP", []))
            signals = [{"id": s["id"], "label": s["label"], "value": readings.get(s["id"], {}).get("value") if reachable else None,
                        "unit": s["unit"], "validity": readings.get(s["id"], {}).get("validity", "unavailable") if reachable else "unavailable",
                        "sampled_at": readings.get(s["id"], {}).get("sampled_at") if reachable else None,
                        "period_ms": s["period_ms"]}
                       for s in systems["sensors"] if s["id"] in unit["sensor_ids"] and s["installed"]]
            invalid = any(s["validity"] == "invalid" for s in signals)
            status = "not_installed" if not module["installed"] else state["status"] if not reachable else "faults" if codes or invalid else "healthy"
            modules.append({"id": id, "label": module["label"], "installed": module["installed"], "status": status,
                            "source": "OBD diagnostic replies and simulation samples" if id == "ecu" else "simulation module state",
                            "codes": sorted(set(codes)) if reachable else [], "pending_codes": sorted(set(pending)) if reachable else [],
                            "signals": signals, "diagnostic_capability": module["capability"], "connection": state,
                            "note": "Generic teaching OBD endpoint" if id == "ecu" else "Lab event labels and sampled values; not a proprietary ECU scan response."})
        return {"t": snapshot.get("t", 0), "connection": self.state(), "modules": modules,
                "module_id": module_id, "diagnostics": diagnostics,
                "scope": "Selected control unit" if module_id is not None else "Only engine ECU byte requests run. Other unit results explicitly inspect the simulation model."}
